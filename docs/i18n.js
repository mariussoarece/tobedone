  // Order shown in the menu
  var ORDER = ["en", "ro", "de", "fr", "es", "it", "pt", "nl", "sv", "nb", "da", "fi", "pl", "tr", "ar", "ja", "zh", "ko", "vi"];
  // Browser codes that map to one of ours
  var ALIAS = { no: "nb", nn: "nb", "zh-hans": "zh", "zh-cn": "zh", "zh-sg": "zh" };

  function pick(code) {
    if (!code) return null;
    code = code.toLowerCase();
    if (T[code]) return code;
    if (ALIAS[code]) return ALIAS[code];
    var base = code.split("-")[0];
    if (T[base]) return base;
    return ALIAS[base] || null;
  }

  function detect() {
    var fromUrl = new URLSearchParams(location.search).get("lang");
    if (pick(fromUrl)) return pick(fromUrl);
    try { var saved = localStorage.getItem("tobedone-lang"); if (pick(saved)) return pick(saved); } catch (e) {}
    var langs = navigator.languages || [navigator.language];
    for (var i = 0; i < langs.length; i++) { var p = pick(langs[i]); if (p) return p; }
    return "en";
  }

  function apply(code) {
    var d = T[code] || T.en;
    document.documentElement.lang = code;
    document.documentElement.dir = d.dir || "ltr";
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      var value = d[key] != null ? d[key] : T.en[key];
      if (key === "t") { document.title = value; return; }
      if (key === "appLang") { el.hidden = !value; }
      el.innerHTML = value;   // our own strings only, may contain <b> and <br>
    });
    var sel = document.getElementById("lang-select");
    if (sel) sel.value = code;
  }

  var sel = document.getElementById("lang-select");
  ORDER.forEach(function (code) {
    var o = document.createElement("option");
    o.value = code; o.textContent = T[code].name;
    sel.appendChild(o);
  });
  sel.addEventListener("change", function () {
    try { localStorage.setItem("tobedone-lang", sel.value); } catch (e) {}
    apply(sel.value);
  });

  apply(detect());
